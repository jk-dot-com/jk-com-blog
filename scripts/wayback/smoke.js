const B = "https://blog.jaysonknight.com";
const UA = { headers: { "User-Agent": "Mozilla/5.0" } };
const get = async (p) => {
	const r = await fetch(B + p, { ...UA, redirect: "manual" });
	return { s: r.status, l: r.headers.get("location"), t: r.status < 300 ? await r.text() : "" };
};
const rows = [];
const chk = (n, ok, d = "") => rows.push((ok ? "ok   " : "FAIL ") + n + (d ? "  " + d : ""));
(async () => {
	let r = await get("/");
	chk("home 200", r.s === 200);
	chk("home has chips", /class="card-tag"|class="featured-tag"/.test(r.t));
	chk("home self-canonical", r.t.includes('rel="canonical" href="https://blog.jaysonknight.com/"'));
	r = await get("/posts");
	chk("/posts 200 + rel=next", r.s === 200 && /rel="next"/.test(r.t));
	chk("/posts chips", /class="post-tag"/.test(r.t));
	chk("/posts under 120KB", r.t.length < 120000, Math.round(r.t.length / 1024) + "KB");
	r = await get("/posts?page=2");
	chk("page 2 canonical is itself", r.t.includes("?page=2\""));
	r = await get("/posts?page=999");
	chk("page past the end is 404", r.s === 404);
	r = await get("/category/technology");
	chk("category 200 + chips", r.s === 200 && /class="card-tag"/.test(r.t));
	r = await get("/category/tech");
	chk("merged category 301", r.s === 301, r.l || "");
	r = await get("/tag/cloud");
	chk("tag page 200", r.s === 200);
	r = await get("/posts/what-a-day");
	chk("post: Filed under chip", /Filed under/.test(r.t) && /meta-tag/.test(r.t));
	chk("post: csharp code block", /language-csharp/.test(r.t));
	chk("post: lead not duplicated", !/article-excerpt/.test(r.t));
	r = await get("/posts/httphandler-custom-isapi-extension-mapping");
	const pres = (r.t.match(/<pre/g) || []).length;
	chk("code post: 3 code blocks", pres === 3, String(pres));
	chk("code post: closing tag restored", r.t.includes("&lt;/httpHandlers&gt;") || r.t.includes("</httpHandlers>"));
	r = await get("/posts/scobles-leaving-microsoft");
	chk("image-only post has its note", /no longer available/.test(r.t));
	r = await get("/blog/archive/2005/02/15/1013.aspx");
	chk("old .aspx post URL redirects", r.s === 301, r.l || "");
	r = await get("/jayson/archive/2005/03.aspx");
	chk("old month page redirects", r.s === 301, r.l || "");
	r = await get("/sitemap.xml");
	chk("sitemap index lists posts + pages", r.s === 200 && r.t.includes("sitemap-posts.xml") && r.t.includes("sitemap-pages.xml"));
	r = await get("/robots.txt");
	chk("robots lists the sitemap", r.t.includes("Sitemap: https://blog.jaysonknight.com/sitemap.xml"));
	r = await get("/rss.xml");
	chk("rss has items", r.s === 200 && r.t.includes("<item>"));
	const m = await fetch("https://jaysonknight.com/sitemap-index.xml", UA).then((x) => x.text());
	chk("main-site sitemap index lists the blog", m.includes("blog.jaysonknight.com/sitemap-posts.xml"));
	console.log(rows.join("\n"));
	console.log("FAILS:", rows.filter((x) => x.startsWith("FAIL")).length);
})();
